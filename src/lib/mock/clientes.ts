// `new Date("2026-06-30")` interpreta como medianoche UTC y termina
// mostrando el día anterior al convertir a America/Bogota para mostrarla).
function fecha(year: number, month: number, day: number): Date {
  return new Date(year, month - 1, day, 12, 0, 0);
}

